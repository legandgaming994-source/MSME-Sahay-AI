"""Pure unit tests for deterministic invoice validation (msme.documents.checks / extraction.flatten).

GSTIN vectors come from three independent published sources (not generated by this code):
27AAPFU0939F1ZV, 09AAACT2727Q1ZU, 27AABCU9603R1ZN.
"""

from datetime import date

import pytest

from msme.documents.checks import (FieldMeta, _ALPHA36, gstin_check_char, gstin_problem, money,
                                   normalise_business_key, validate)
from msme.documents.extraction import SEVERITY_CONFIRMED, SEVERITY_HEURISTIC, flatten, scrub

REAL_GSTINS = ["27AAPFU0939F1ZV", "09AAACT2727Q1ZU", "27AABCU9603R1ZN"]
TODAY = date(2026, 10, 17)


def codes(issues, severity=None):
    return sorted(i.code for i in issues if severity is None or i.severity == severity)


def clean(**over):
    values = {
        "invoice_number": "INV-0042", "issue_date": "2026-09-01", "seller.name": "Northgate Supplies",
        "seller.tax_ids[0].value": "27AAPFU0939F1ZV", "seller.tax_ids[0].scheme": "gst",
        "buyer.tax_ids[0].value": "09AAACT2727Q1ZU", "buyer.tax_ids[0].scheme": "gst",
        "line_items[0].quantity": "10", "line_items[0].unit_price": "100.00", "line_items[0].total": "1000.00",
        "line_items[1].quantity": "2", "line_items[1].unit_price": "250.00", "line_items[1].total": "500.00",
        "subtotal": "1500.00", "tax_rate_percent": "18", "tax_amount": "270.00", "total_amount": "1770.00",
    }
    values.update(over)
    return {k: v for k, v in values.items() if v is not None}


# --- GSTIN ------------------------------------------------------------------

def test_real_gstins_pass():
    for g in REAL_GSTINS:
        assert gstin_problem(g) is None and gstin_problem(g.lower()) is None
        assert gstin_check_char(g[:14]) == g[14]


def test_every_single_character_substitution_is_detected():
    for g in REAL_GSTINS:
        for pos in range(14):
            for ch in _ALPHA36:
                if ch != g[pos]:
                    assert gstin_problem(g[:pos] + ch + g[pos + 1:]) is not None, (g, pos, ch)


def test_adjacent_transpositions_and_structure_errors_detected():
    g = REAL_GSTINS[0]
    for pos in range(13):
        if g[pos] != g[pos + 1]:
            swapped = g[:pos] + g[pos + 1] + g[pos] + g[pos + 2:]
            assert gstin_problem(swapped) is not None, swapped
    assert "14 characters" in gstin_problem(g[:14])
    assert "structure" in gstin_problem(g[:13] + "X" + g[14])         # position 14 must be Z
    assert "structure" in gstin_problem("X" + g[1:])                  # state code must be two digits
    assert gstin_problem("27ABCDE1234F1Z5") is not None  # documentation example from a blog: not a real checksum


# --- arithmetic ---------------------------------------------------------------

def test_clean_invoice_has_no_issues():
    assert validate(clean(), today=TODAY) == []


def test_line_total_mismatch_confirmed():
    out = validate(clean(**{"line_items[0].total": "900.00", "subtotal": "1400.00", "total_amount": "1652.00",
                            "tax_amount": "252.00"}), today=TODAY)
    assert "LINE_TOTAL_MISMATCH" in codes(out, SEVERITY_CONFIRMED)


def test_line_rounding_within_half_a_unit_per_quantity_is_not_flagged():
    # 3 x 33.33 = 99.99 printed as 100.00 (unit price rounded to paise)
    v = clean(**{"line_items[0].quantity": "3", "line_items[0].unit_price": "33.33", "line_items[0].total": "100.00",
                 "line_items[1].total": "500.00", "subtotal": "600.00", "tax_amount": "108.00", "total_amount": "708.00"})
    assert "LINE_TOTAL_MISMATCH" not in codes(validate(v, today=TODAY))


def test_subtotal_mismatch_confirmed():
    out = validate(clean(subtotal="1600.00", total_amount="1870.00", tax_amount="270.00"), today=TODAY)
    assert "SUBTOTAL_MISMATCH" in codes(out, SEVERITY_CONFIRMED)


def test_total_mismatch_confirmed_and_round_off_heuristic():
    big = validate(clean(total_amount="1800.00"), today=TODAY)
    assert "TOTAL_MISMATCH" in codes(big, SEVERITY_CONFIRMED)
    rounded = validate(clean(total_amount="1770.40"), today=TODAY)
    assert codes(rounded) == ["POSSIBLE_ROUND_OFF"] and rounded[0].severity == SEVERITY_HEURISTIC
    assert validate(clean(total_amount="1770.01"), today=TODAY) == []


def test_discount_and_shipping_enter_the_total():
    v = clean(discount_amount="100.00", shipping_amount="50.00", tax_amount="270.00", total_amount="1720.00")
    assert "TOTAL_MISMATCH" not in codes(validate(v, today=TODAY))


def test_tax_rate_mismatch_is_only_heuristic():
    out = validate(clean(tax_amount="150.00", total_amount="1650.00"), today=TODAY)
    assert codes(out) == ["TAX_RATE_MISMATCH"] and out[0].severity == SEVERITY_HEURISTIC


def test_indian_number_formatting_is_parsed():
    assert str(money("₹ 1,23,456.50")) == "123456.50" and str(money("Rs. 1,000")) == "1000"
    assert money("abc") is None and money(None) is None


# --- identifiers, dates, completeness ----------------------------------------------

def test_invalid_gstin_confirmed_with_path():
    out = validate(clean(**{"seller.tax_ids[0].value": "27AAPFU0939F1ZW"}), today=TODAY)
    hit = [i for i in out if i.code == "GSTIN_INVALID"]
    assert hit and hit[0].severity == SEVERITY_CONFIRMED and hit[0].field_path == "seller.tax_ids[0].value"


def test_non_gst_scheme_is_not_checked_as_gstin():
    out = validate(clean(**{"seller.tax_ids[0].value": "DE136695976", "seller.tax_ids[0].scheme": "vat"}), today=TODAY)
    assert "GSTIN_INVALID" not in codes(out)


def test_missing_required_and_date_rules():
    out = validate(clean(invoice_number=None, **{"seller.name": " "}), today=TODAY)
    assert codes(out, SEVERITY_CONFIRMED).count("MISSING_REQUIRED") == 2
    assert "DUE_BEFORE_ISSUE" in codes(validate(clean(due_date="2026-08-01"), today=TODAY))
    assert "DATE_IN_FUTURE" in codes(validate(clean(issue_date="2026-12-01"), today=TODAY))
    assert "DATE_UNPARSEABLE" in codes(validate(clean(issue_date="01/09/2026"), today=TODAY))


def test_evidence_quality_flags_only_key_fields():
    meta = {"total_amount": FieldMeta(0.55, "verified"), "invoice_number": FieldMeta(None, "unlocated"),
            "issue_date": FieldMeta(0.99, "verified"), "buyer.name": FieldMeta(0.1, "verified")}
    out = validate(clean(**{"buyer.name": "B"}), meta, today=TODAY)
    assert codes(out) == ["CITATION_UNLOCATED", "LOW_CONFIDENCE"]
    assert all(i.severity == SEVERITY_HEURISTIC for i in out)


# --- business key / flatten / scrub --------------------------------------------------

def test_business_key_ignores_formatting_but_not_substance():
    a = normalise_business_key(clean())
    b = normalise_business_key(clean(invoice_number="inv 0042", total_amount="1,770.00",
                                     **{"seller.tax_ids[0].value": "27aapfu0939f1zv"}))
    assert a == b and a.startswith("27AAPFU0939F1ZV|INV0042|2026-09-01|1770.00")
    assert normalise_business_key(clean(total_amount="1771.00")) != a
    assert normalise_business_key(clean(invoice_number=None)) is None
    name_only = clean(**{"seller.tax_ids[0].value": None})
    assert normalise_business_key(name_only).startswith("northgatesupplies|")


def test_flatten_matches_docket_path_style_and_skips_internals():
    data = {"invoice_number": "X1", "total_amount": 1770.0, "seller": {"name": "S", "tax_ids": [{"value": "V"}]},
            "line_items": [{"total": 5.5}], "note": None, "_internal": 1, "field_locations": {"a": {}}}
    assert dict(flatten(data)) == {"invoice_number": "X1", "total_amount": "1770", "seller.name": "S",
                                   "seller.tax_ids[0].value": "V", "line_items[0].total": "5.5"}


def test_scrub_redacts_secrets_and_truncates():
    out = scrub("auth failed with Bearer abc.def.ghi and key sk-ABCDEFGH12345 \n then api_key=hunter2")
    assert "abc.def" not in out and "sk-ABCDEFGH" not in out and "hunter2" not in out and "\n" not in out
    assert len(scrub("x" * 1000)) == 300
